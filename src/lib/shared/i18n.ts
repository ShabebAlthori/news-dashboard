const dictionaries: Record<Lang, Record<I18nKey, Entry>> = { en, ar };

const pluralRules: Record<Lang, Intl.PluralRules> = {
  en: new Intl.PluralRules("en"),
  ar: new Intl.PluralRules("ar"),
};

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const entry = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  let text: string;
  if (typeof entry === "string") {
    text = entry;
  } else {
    const n = Number(vars?.n ?? 0);
    const category = n === 0 && entry.zero ? "zero" : pluralRules[lang].select(n);
    text = (entry as Record<string, string | undefined>)[category] ?? entry.other;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
